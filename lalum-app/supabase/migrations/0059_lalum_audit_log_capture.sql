-- 0059: the audit log as it runs in the live project, so a fresh database can be built from this repository.
--
-- Until now the audit log (SEC-16) existed only in the live project: no migration in this repository creates
-- public.lalum_matter_audit_log, lalum_audit_hash, lalum_append_audit, lalum_verify_audit_chain, lalum_audit_immutable
-- or the trigger lalum_audit_no_update. This file captures them exactly as read from the live project on
-- 2026-10-20 (pg_get_functiondef, pg_constraint, pg_indexes, pg_policies).
--
-- It must not change the live project, so the whole file is one guarded block that does nothing when the table
-- already exists (the live case), and also does nothing, with a notice, when what the table depends on is absent.
-- Migration numbers are claimed by several sessions: renumber at merge time if 0059 is taken.

do $$
begin
  if to_regclass('public.lalum_matter_audit_log') is not null then
    raise notice '0059: public.lalum_matter_audit_log exists, nothing to capture';
    return;
  end if;
  if to_regclass('public.lalum_firms') is null
     or to_regclass('public.lalum_cockpit_matters') is null
     or to_regprocedure('public.lalum_my_firm_id()') is null
     or to_regprocedure('public.lalum_my_role()') is null
     or to_regprocedure('public.lalum_is_admin()') is null
     or to_regprocedure('extensions.digest(bytea,text)') is null then
    raise notice '0059: dependencies of the audit log are not present (firms, matters, role helpers, pgcrypto), skipped';
    return;
  end if;

  create table public.lalum_matter_audit_log (
    id             bigint generated by default as identity primary key,
    firm_id        uuid not null references public.lalum_firms(id) on delete cascade,
    seq            bigint not null,
    matter_id      uuid references public.lalum_cockpit_matters(id) on delete set null,
    attorney_id    uuid,
    action         text not null,
    ai_output_hash text not null default '',
    meta           jsonb not null default '{}'::jsonb,
    prev_hash      text not null,
    hash           text not null,
    "timestamp"    timestamptz not null default clock_timestamp(),
    unique (firm_id, seq)
  );
  create index lalum_matter_audit_log_matter_idx on public.lalum_matter_audit_log (matter_id);
  alter table public.lalum_matter_audit_log enable row level security;

  create policy lalum_audit_read on public.lalum_matter_audit_log for select using (
    ((firm_id = public.lalum_my_firm_id()) and (public.lalum_my_role() = any (array['FIRM_PARTNER'::text, 'COMPLIANCE_OFFICER'::text, 'ADMIN'::text])))
    or public.lalum_is_admin()
  );

  create or replace function public.lalum_audit_hash(p_prev text, p_seq bigint, p_firm uuid, p_matter uuid, p_actor uuid, p_action text, p_ai_hash text, p_meta jsonb, p_ts timestamp with time zone)
   returns text
   language sql
   immutable
   set search_path to 'public', 'extensions'
  as $f$
    select encode(extensions.digest(convert_to(concat_ws('|',
      p_prev, p_seq::text, p_firm::text, coalesce(p_matter::text,''), coalesce(p_actor::text,''),
      p_action, coalesce(p_ai_hash,''), p_meta::text,
      to_char(p_ts at time zone 'utc','YYYY-MM-DD"T"HH24:MI:SS.US"Z"')
    ), 'utf8'), 'sha256'), 'hex') $f$;

  create or replace function public.lalum_audit_immutable()
   returns trigger
   language plpgsql
   set search_path to ''
  as $f$
  begin raise exception 'lalum_matter_audit_log is append-only'; end $f$;

  create trigger lalum_audit_no_update before delete or update on public.lalum_matter_audit_log
    for each row execute function public.lalum_audit_immutable();

  create or replace function public.lalum_append_audit(p_firm uuid, p_matter uuid, p_actor uuid, p_action text, p_ai_hash text, p_meta jsonb default '{}'::jsonb)
   returns bigint
   language plpgsql
   security definer
   set search_path to 'public', 'extensions'
  as $f$
  declare v_seq bigint; v_prev text; v_ts timestamptz := clock_timestamp(); v_id bigint;
  begin
    if p_meta::text ~* '[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}' then
      raise exception 'refusing to write an e-mail address into the audit log';
    end if;
    perform pg_advisory_xact_lock(hashtextextended('lalum_audit:' || p_firm::text, 0));
    select seq, hash into v_seq, v_prev from public.lalum_matter_audit_log
     where firm_id = p_firm order by seq desc limit 1;
    v_seq := coalesce(v_seq, 0) + 1;
    v_prev := coalesce(v_prev, repeat('0', 64));
    insert into public.lalum_matter_audit_log
      (firm_id, seq, matter_id, attorney_id, action, ai_output_hash, meta, prev_hash, hash, "timestamp")
    values (p_firm, v_seq, p_matter, p_actor, p_action, coalesce(p_ai_hash,''), coalesce(p_meta,'{}'::jsonb), v_prev,
            public.lalum_audit_hash(v_prev, v_seq, p_firm, p_matter, p_actor, p_action, coalesce(p_ai_hash,''), coalesce(p_meta,'{}'::jsonb), v_ts),
            v_ts)
    returning id into v_id;
    return v_id;
  end $f$;

  create or replace function public.lalum_verify_audit_chain(p_firm uuid)
   returns bigint
   language plpgsql
   stable security definer
   set search_path to 'public', 'extensions'
  as $f$
  declare r record; v_prev text := repeat('0', 64); v_expected bigint := 1;
  begin
    if not (public.lalum_is_admin() or p_firm = public.lalum_my_firm_id()) then
      raise exception 'not authorized';
    end if;
    for r in select * from public.lalum_matter_audit_log where firm_id = p_firm order by seq loop
      if r.seq <> v_expected or r.prev_hash <> v_prev
         or r.hash <> public.lalum_audit_hash(r.prev_hash, r.seq, r.firm_id, r.matter_id, r.attorney_id, r.action, r.ai_output_hash, r.meta, r."timestamp") then
        return r.seq;
      end if;
      v_prev := r.hash; v_expected := v_expected + 1;
    end loop;
    return null;
  end $f$;

  -- Table grants as read live before 0060 narrowed them (Supabase's default privileges gave them there; a plain
  -- database has none, so they are stated here). 0060 then removes what the app never needs.
  grant all on table public.lalum_matter_audit_log to service_role;
  grant select, references, trigger on table public.lalum_matter_audit_log to authenticated;

  -- Function grants as read from the live project on 2026-10-20: the append, hash and trigger functions run only
  -- for service_role; the chain check is also open to signed in users (it checks the caller's firm itself).
  revoke all on function public.lalum_append_audit(uuid, uuid, uuid, text, text, jsonb) from public, anon, authenticated;
  revoke all on function public.lalum_audit_hash(text, bigint, uuid, uuid, uuid, text, text, jsonb, timestamptz) from public, anon, authenticated;
  revoke all on function public.lalum_audit_immutable() from public, anon, authenticated;
  revoke all on function public.lalum_verify_audit_chain(uuid) from public, anon;
  grant execute on function public.lalum_append_audit(uuid, uuid, uuid, text, text, jsonb) to service_role;
  grant execute on function public.lalum_audit_hash(text, bigint, uuid, uuid, uuid, text, text, jsonb, timestamptz) to service_role;
  grant execute on function public.lalum_audit_immutable() to service_role;
  grant execute on function public.lalum_verify_audit_chain(uuid) to authenticated, service_role;
end $$;
