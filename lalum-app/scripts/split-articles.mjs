// Split the article corpus, and precompute what the pages used to derive from
// it at runtime.
//
// The problem this solves, measured: every content page pulled one 451KB
// (gzipped) chunk holding the body of all 169 articles. An article page needs
// exactly one of those bodies, and the articles index needs none of them, since
// it shows titles and standfirsts. It was pulling them because two things were
// computed from the bodies while the page rendered: which topic hub an article
// belongs to, and which three articles to offer at its foot.
//
// Both are pure functions of a corpus that only changes when someone writes an
// article, so they are computed here instead, with the very same functions the
// pages used, and written to src/data/articleIndex.json. The bodies are written
// out one file per article, so an article page loads its own and nothing else.
//
// Run it after adding or editing an article:
//
//   npm run split-articles
//
// `npm run build` fails when the index does not cover every article, so a
// forgotten run is caught rather than silently serving a stale classification.

import { mkdirSync, writeFileSync, readdirSync, rmSync, existsSync } from "node:fs";
import { join } from "node:path";
import { createServer } from "vite";

const ROOT = join(import.meta.dirname, "..");
const POSTS_DIR = join(ROOT, "src", "data", "posts");
const INDEX_FILE = join(ROOT, "src", "data", "articleIndex.json");

const server = await createServer({ server: { middlewareMode: true }, appType: "custom", logLevel: "error" });

try {
  const { blogPosts } = await server.ssrLoadModule("/src/lib/blogPosts.ts");
  const { strings } = await server.ssrLoadModule("/src/lib/strings.ts");
  const { classifyCorpus } = await server.ssrLoadModule("/src/lib/topics.ts");
  const { scoringCorpus, scoreRelated } = await server.ssrLoadModule("/src/lib/related.ts");

  const dict = strings.he;

  // The expensive forms, run here and only here.
  const byTopic = classifyCorpus(dict, blogPosts);
  const topicOf = new Map();
  for (const [topicSlug, rows] of byTopic) for (const r of rows) topicOf.set(r.slug, topicSlug);

  const corpus = scoringCorpus(dict, blogPosts);

  const index = {};
  for (const a of corpus) {
    index[a.slug] = {
      topic: topicOf.get(a.slug) ?? null,
      related: scoreRelated(a.slug, corpus).map((r) => r.slug),
    };
  }

  // One module per body. The name is the slug, which is what the page has in
  // hand when it needs the body, so the lookup needs no table.
  if (existsSync(POSTS_DIR)) {
    for (const f of readdirSync(POSTS_DIR)) rmSync(join(POSTS_DIR, f));
  }
  mkdirSync(POSTS_DIR, { recursive: true });

  for (const post of blogPosts) {
    const file = join(POSTS_DIR, `${post.slug}.ts`);
    writeFileSync(
      file,
      `// Generated by scripts/split-articles.mjs. Edit the body in src/lib/blogPosts.ts.\nexport const body = ${JSON.stringify(post.body)};\n`,
      "utf8",
    );
  }

  writeFileSync(INDEX_FILE, `${JSON.stringify(index, null, 1)}\n`, "utf8");

  const missing = Object.values(index).filter((e) => !e.topic || e.related.length !== 3).length;
  console.log(`[split-articles] ${blogPosts.length} bodies written, ${Object.keys(index).length} articles indexed${missing ? `, ${missing} incomplete` : ""}`);
  if (missing) process.exitCode = 1;
} finally {
  await server.close();
}
