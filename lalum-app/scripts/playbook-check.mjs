// Checks the real estate playbook patterns (supabase/playbooks/real_estate.json) against labelled clauses
// (real_estate.cases.json), with the same matching the pipeline uses (punctuation normalised, flags "iu",
// ABSENT fires when nothing matches, PRESENT fires when something does). Also verifies that migration 0043 is exactly what
// this file generates, so the data and the migration cannot drift. Run: npm run playbook-check. Regenerate the
// migration: node scripts/playbook-check.mjs --write
import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../supabase/playbooks/", import.meta.url);
const pb = JSON.parse(readFileSync(new URL("real_estate.json", dir), "utf8"));
const { cases, complete_agreement } = JSON.parse(readFileSync(new URL("real_estate.cases.json", dir), "utf8"));
const MIG = new URL("../supabase/migrations/0043_lalum_real_estate_playbook.sql", import.meta.url);

const norm = (s) => s.replace(/[״“”]/g, '"').replace(/[׳‘’]/g, "'");
const fires = (rule, pattern, text) => { const m = new RegExp(pattern, "iu").test(norm(text)); return rule.mode === "PRESENT" ? m : !m; };
const all = [...pb.rules, ...pb.new_rules];
const byName = new Map(all.map((r) => [r.rule_name, r]));

let wrong = 0, wrongBefore = 0, total = 0, beforeTotal = 0;
const perRule = new Map();
for (const c of cases) {
  const r = byName.get(c.rule); assert.ok(r, `case names an unknown rule: ${c.rule}`);
  total++;
  const now = fires(r, r.pattern, c.text);
  if (now !== c.fires) { wrong++; console.error(`FAIL  [${c.rule}] expected ${c.fires ? "fires" : "quiet"}: ${c.text}`); }
  if (r.previous) {
    beforeTotal++;
    const was = fires(r, r.previous, c.text);
    const p = perRule.get(c.rule) ?? { n: 0, before: 0 }; p.n++;
    if (was !== c.fires) { wrongBefore++; p.before++; }
    perRule.set(c.rule, p);
  }
}
// every active rule needs at least two cases of each outcome
for (const r of all) {
  const mine = cases.filter((c) => c.rule === r.rule_name);
  assert.ok(mine.some((c) => c.fires) && mine.filter((c) => !c.fires).length >= 2 && mine.length >= 4, `rule needs cases of both outcomes: ${r.rule_name}`);
  assert.doesNotThrow(() => new RegExp(r.pattern, "iu"), `pattern compiles: ${r.rule_name}`);
}
// a complete set of clauses must leave every active rule quiet (PRESENT rules would fire on waivers, so skip those)
for (const r of pb.rules.filter((x) => x.mode === "ABSENT")) assert.equal(fires(r, r.pattern, complete_agreement), false, `complete agreement fires ${r.rule_name}`);
// nothing fires on empty text except ABSENT rules, and no PRESENT rule fires on it
for (const r of all) assert.equal(fires(r, r.pattern, ""), r.mode === "ABSENT", `empty text: ${r.rule_name}`);
// patterns must not be able to hang: a long text with repeated near matches stays fast
const long = ("הערת אזהרה ".repeat(4000) + "ערבות ".repeat(4000) + "שכר טרחת ".repeat(4000));
const t0 = Date.now(); for (const r of all) new RegExp(r.pattern, "iu").test(norm(long)); assert.ok(Date.now() - t0 < 2000, "patterns are fast on long text");

// migration text
const q = (s) => `$pb$${s}$pb$`;
const lines = [
  "/* Real estate playbook: urban renewal (פינוי-בינוי) patterns. Generated by scripts/playbook-check.mjs --write from supabase/playbooks/real_estate.json, do not edit by hand.",
  "   Existing rules: only the pattern changes, and only where the live pattern still equals the one this was written against (a rule edited by hand since is left alone).",
  "   New rules are inserted INACTIVE. A partner turns each on after reading its description and fallback clause.",
  "   Hits on the labelled clauses in real_estate.cases.json: see the check script. Not applied to production until approved. */",
];
for (const r of pb.rules) lines.push(`update public.lalum_practice_playbooks set pattern = ${q(r.pattern)}, updated_at = now() where practice_area = ${q(pb.practice_area)} and rule_name = ${q(r.rule_name)} and pattern = ${q(r.previous)};`);
for (const r of pb.new_rules) lines.push(`insert into public.lalum_practice_playbooks (practice_area, rule_name, severity, description, fallback_clause, mode, pattern, source_citation, active) select ${q(pb.practice_area)}, ${q(r.rule_name)}, ${q(r.severity)}, ${q(r.description)}, ${q(r.fallback_clause)}, ${q(r.mode)}, ${q(r.pattern)}, ${q(r.source_citation)}, false where not exists (select 1 from public.lalum_practice_playbooks where practice_area = ${q(pb.practice_area)} and rule_name = ${q(r.rule_name)});`);
const sql = lines.join("\n") + "\n";
if (process.argv.includes("--write")) { writeFileSync(MIG, sql); console.log("migration written"); }
else assert.equal(readFileSync(MIG, "utf8"), sql, "migration 0043 differs from what real_estate.json generates (run with --write)");

for (const [k, v] of perRule) console.log(`${k}: wrong before ${v.before}/${v.n}`);
console.log(`cases: ${total}, wrong now ${wrong}; previous patterns wrong ${wrongBefore}/${beforeTotal}`);
if (wrong) process.exit(1);
console.log("playbook-check: ok");
