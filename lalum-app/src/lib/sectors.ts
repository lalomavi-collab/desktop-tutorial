// Sector rubrics: the AI practice cut by the kind of body it serves, rather
// than by the legal subject. A local authority, a government ministry and a
// health fund all face "AI governance", but they face it under different
// duties, with different decision makers and different failure modes, and a
// page written for all of them is a brochure. A page written for one of them
// is something you can send to that one.
//
// The first rubric is local authorities. Each further body is one more object
// in SECTORS: the route, the prerender, the sitemap and the AI pillar page all
// read this list, so adding a sector is a content edit and not a code change.
//
// The page carries three rubrics, in the order a municipal reader needs them:
// what the courts have already decided, what the regulator has already
// instructed, and what the authority can do about it on Monday morning.
//
// Two rules govern what may be published here, and they are the reason the
// case law section reads from rulings.ts rather than holding its own copy:
//
//   1. No citation without a source. A page that tells authorities not to
//      trust unverified AI output cannot itself carry a case number nobody
//      opened. Every ruling below is a record in the verified corpus, with its
//      court, its date and its public sources.
//   2. What was decided is separated from what was said. The Ramat Gan ruling
//      decided costs; its administrative law observations are obiter, and are
//      presented as such. Overstating them would be the same failure in the
//      other direction.
//
// Hebrew only, deliberately. The audience is Israeli municipal management and
// its legal advisors; a translated rendering would claim an alternate that
// does not exist. The route is therefore absent from TRANSLATED_ROUTES in
// hreflang.ts and carries no language alternates.

export type SectorCard = { icon: IconName; title: string; body: string };
export type SectorStep = { n: string; title: string; body: string };

// A ruling shown in the case law rubric. `id` points into the verified corpus,
// so the citation, court, bench and sources have exactly one home; `why` is
// what this audience should take from it.
export type SectorCase = { id: string; why: string };

// A published regulator instruction. `source` links the instrument itself, so
// a legal advisor can read it rather than take our word for it.
export type SectorDirective = {
  icon: IconName;
  title: string;
  body: string;
  points: string[];
  sourceLabel: string;
  sourceHref: string;
};

// A working tool: a protocol or a checklist the authority can adopt as is.
// This is the part that replaces the brochure, so it is written to be used and
// not to be admired.
export type SectorTool = {
  icon: IconName;
  title: string;
  intro: string;
  kind: "protocol" | "checklist";
  items: { title: string; body: string }[];
  note?: string;
};

// One item in the living materials list. Outreach points an authority here
// instead of at a PDF, so the page has to be worth returning to. `note` says
// what the item gives *this* audience, because a list of titles is a link dump
// and not a rubric.
// A file the reader takes away. The booklet is generated from this same
// Sector at build time, so the document a municipality downloads and the page
// it downloaded it from cannot drift apart. Nothing is hand-authored twice.
export type SectorDownload = { title: string; note: string; file: string; updated: string };

// The self-assessment. Five binary questions, each worth 20 points of exposure
// when the answer is no, and each carrying the remedy it points at. The copy
// stays on ground that can be defended: what the Supreme Court actually said
// about an unreasoned, unchecked decision, and what the regulator is actually
// empowered to do. A tool that overstates the law to frighten a CEO is the
// same defect as a brochure that does it, and it is easier to check.
export type AuditQuestion = { id: string; q: string; why: string; fix: string };
export type AuditBand = { id: "low" | "medium" | "high"; upTo: number; label: string; body: string };

export type MaterialKind = "article" | "course" | "check" | "ruling";
export type SectorMaterial = { kind: MaterialKind; title: string; note: string; href: string; date: string };

