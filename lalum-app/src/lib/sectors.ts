// Resolve a sector's case references against the verified corpus. A reference
// to an id that is not in the corpus resolves to nothing and the card is not
// rendered, which is the safe direction: a missing card is a gap, a card with
// an unverified citation is the failure this page is about.
export function sectorCases(sector: Sector): { ruling: Ruling; why: string }[] {
  return sector.cases
    .map((c) => ({ ruling: rulings.find((r) => r.id === c.id), why: c.why }))
    .filter((x): x is { ruling: Ruling; why: string } => Boolean(x.ruling));
}

