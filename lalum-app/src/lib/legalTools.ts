// The interactive tools on the AI pillar. Each is the same instrument, a run
// of binary questions producing an exposure score and a gap map, pointed at a
// different subject, so they share one engine (components/Diagnostic.tsx) and
// differ only in their data and in whatever each produces at the end.
//
// Two rules govern the copy here, and they are the same two that govern the
// case law on the sector pages:
//
//   1. Nothing is asserted that has not been verified. The specification these
//      tools were written from carried a fine of a stated amount, direct
//      criminal liability for a CEO, and an average court delay of three to six
//      years. None of those could be sourced, so none of them are here. What is
//      here instead is what the Supreme Court actually said about an unreasoned
//      and unchecked decision, and what the regulator is actually empowered to
//      do. A tool that overstates the law to frighten an executive is the same
//      defect as a brochure that does it, and it is easier to check.
//   2. Nothing is claimed about the courts that we cannot stand behind. The
//      comparison in the dispute tool therefore sets out what each route is
//      structurally, not how long it statistically takes.
//
// Answers never leave the browser. That is what lets these pages promise an
// executive that a self-assessment of their own exposure is not a lead form.

